void set_histogram(Numbers numbers, Histogram &histogram, Histogram &histogram_pos) {

    bool is_odd = (numbers.size() % 2 == 1);
    int half_length = numbers.size()/2;

    int left = 0;
    int right = numbers.size() - 1;

    int a;
    int b;

    for (int i = 0; i < half_length; i++) {
        
        a = numbers[left + i];
        b = numbers[right - i];

        if ((histogram).count(a) == 0) {
            (histogram)[a] = 0;

            if (a > 0)
                histogram_pos[a] = 1;

        }
        (histogram)[a] += 1;
        
        if ((histogram).count(b) == 0) {
            (histogram)[b] = 0;

            if (b > 0)
                histogram_pos[b] = 1;

        }
        (histogram)[b] += 1;
    }

    if (is_odd) {
        
        a = numbers[half_length];

         if ((histogram).count(a) == 0) {
            (histogram)[a] = 0;
            
            if (a > 0)
                histogram_pos[a] = 1;
        }
        (histogram)[a] += 1;
    }
}

void sort_list(Numbers &numbers) {

    std::sort(numbers.begin(), numbers.end(), [](int a, int b){  return a < b ; });

}

void sort_list(Nodes & nodes) {

    std::sort(nodes.begin(), nodes.end(), [](Node *node_a, Node* node_b){  return node_a->acc < node_b->acc ; });

}


void process_value (const int &value,  const Histogram histo,   Numbers data, std::map<int, std::map<int, std::map<int, void*>>> &path_map, std::vector<Numbers > &data_return) {

    Histogram histogram_pad = histo;

    if (histo.count(value)) {
        
        std::sort(data.begin(), data.end(), [](int a, int b) {return a < b;});

        int sum = std::accumulate(data.begin(), data.end(), 0);
        
        histogram_pad = histo;
        
        if (sum == 0) {
            
            bool bin_exhausted = false;
            
            for (const auto &c: data) {
                bin_exhausted |= +( histogram_pad[c] <= 0 );
                histogram_pad[c]+= -1;
            } 

            if ( !bin_exhausted && path_map[ data[0] ][ data[1]].count(data[2])  == 0) {
            
                // catch if fetch fails 
                
                path_map[ data[0] ][ data[1]][data[2]] = nullptr;
                
                // std::cout << data;
                data_return.push_back(data);

            }  
            
        }

    }
}


void move_to_node (Nodes *nodes, const Numbers & numbers, Histogram histo) {
    
    for (const auto &data: numbers) {

        nodes[0].push_back(new Node{ data, {data}, histo});
    }

}

void uniquify (Nodes &nodes) {

    std::size_t k = 0;
    while (k + 1 < nodes.size()) {
        if (nodes[k]->acc  == nodes[k + 1]->acc ) {
            delete nodes[k + 1]; // free 
            nodes.erase(nodes.begin() + k+1); // Deletes element at specific index
        } else {
            k++;
        }
    }
}

void uniquify (Numbers &numbers) {

    std::size_t k = 0;
    while (k + 1 < numbers.size()) {
        if (numbers[k] == numbers[k + 1] ) {
            numbers.erase(numbers.begin() + k+1); // Deletes element at specific index
        } else {
            k++;
        }
    }
}



